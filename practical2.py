a = 20
b = 10

# Arithmetic 
print("Addition:", a + b)
print("Division:", a / b)
print("Multiplication:", a * b)
print("Subtraction:", a - b)

# Relational
print("a>b:", a > b)
print("a<b:", a < b)

# Logical
print("a>10 and b<20:", a > 10 and b < 20)

# Bitwise
print("a&b:", a & b)
print("a^b:", a ^ b)
print("~a:", ~a)

# Assignment
a += b
print("Update a:", a)
print("Update b:", b)

# Membership
list1 = [1, 2, 3, 4]
print("2 in list1:", 2 in list1)
print("5 not in list1:", 5 not in list1)

# Identity
x = 10
y = 10
print("x is y:", x is y)